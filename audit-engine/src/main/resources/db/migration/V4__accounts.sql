-- Accounts: users can be invited before they have a password, disabled without being deleted,
-- and set or reset their password through a one-time link.

-- INVITED: has a link but no password yet; ACTIVE: can sign in; DISABLED: refused at sign-in
ALTER TABLE vault_users ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE vault_users ADD COLUMN created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now();
ALTER TABLE vault_users ADD COLUMN last_login_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE vault_users ALTER COLUMN password DROP NOT NULL;

-- Emails are compared without regard to case
UPDATE vault_users SET email = lower(email);

-- A company's email domain is optional; when set, only addresses at that domain can be invited
ALTER TABLE company_tenants ALTER COLUMN allowed_domain DROP NOT NULL;

-- One-time links for accepting an invitation or resetting a password. Only a SHA-256 hash of
-- the link's secret is stored, so a database leak doesn't hand out working links.
CREATE TABLE account_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    user_id     BIGINT NOT NULL REFERENCES vault_users (id),
    purpose     VARCHAR(20) NOT NULL,
    created_by  VARCHAR(255),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX idx_account_tokens_user ON account_tokens (user_id);
