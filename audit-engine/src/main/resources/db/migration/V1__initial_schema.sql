-- Initial schema for the audit engine. Hibernate runs with ddl-auto=validate, so
-- every entity change needs a new migration file (V2__..., V3__...).

CREATE TABLE company_tenants (
    tenant_id      VARCHAR(255) PRIMARY KEY,
    company_name   VARCHAR(255) NOT NULL,
    allowed_domain VARCHAR(255) NOT NULL UNIQUE,
    created_at     TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE vault_users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email     VARCHAR(255) NOT NULL UNIQUE,
    password  VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    tenant_id VARCHAR(255) NOT NULL REFERENCES company_tenants (tenant_id),
    role      VARCHAR(255) NOT NULL
);

CREATE TABLE financial_audit_vault (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         VARCHAR(255) NOT NULL REFERENCES company_tenants (tenant_id),
    document_type      VARCHAR(255) NOT NULL,
    raw_extracted_text TEXT NOT NULL,
    ai_audit_report    TEXT NOT NULL,
    audit_status       VARCHAR(255) NOT NULL,
    vaulted_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_financial_audit_vault_company ON financial_audit_vault (company_id, vaulted_at DESC);

CREATE TABLE company_realtime_metrics (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id             VARCHAR(255) NOT NULL UNIQUE REFERENCES company_tenants (tenant_id),
    total_assets           VARCHAR(255),
    total_liabilities      VARCHAR(255),
    net_equity             VARCHAR(255),
    total_audits_processed INTEGER NOT NULL,
    last_audit_status      VARCHAR(255),
    last_updated           TIMESTAMP(6)
);

-- The vault is append-only. This is enforced in the database so it holds no matter
-- which code path (or SQL client) touches the table. In production, run the app as a
-- role that does not own this table, so it cannot drop the triggers either.
CREATE FUNCTION reject_vault_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'financial_audit_vault is append-only: % is not allowed', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER financial_audit_vault_no_update_delete
    BEFORE UPDATE OR DELETE ON financial_audit_vault
    FOR EACH ROW EXECUTE FUNCTION reject_vault_mutation();

CREATE TRIGGER financial_audit_vault_no_truncate
    BEFORE TRUNCATE ON financial_audit_vault
    FOR EACH STATEMENT EXECUTE FUNCTION reject_vault_mutation();
